"""Sanity checks for the IPCARF 5-outer-fold reference run. usage: python sanity_checks.py [pred_root]
1 split disjointness/coverage by row id; 2 X/Y row alignment by id; 3 prediction shapes and column mapping;
4 per-label Youden threshold is computed on the TEST fold (independent re-implementation matches the authors' evaluator);
5 HMC -> flat mapping evaluates exactly the 44 original diseases."""
import sys, numpy as np, pandas as pd
from sklearn.metrics import roc_curve, roc_auc_score, average_precision_score
AC = "/private/tmp/claude-501/-Users-nazlihosseinipour-git-logicalcollections/d46db87b-e760-4f53-8270-db0680928abb/scratchpad/ipcarf_5fold/authors_copy"
R = "/Users/nazlihosseinipour/Nazli Second Brain/03 Projects/Internship/lncrna-gip-project/results/paper_reproduction_reference_2026-09-20/ipcarf_5fold"
PR = sys.argv[1] if len(sys.argv) > 1 else R
sys.path[:0] = [AC + "/parse_results", AC]
from evaluate import Evaluator
D = AC + "/create_dataset/datasets/"
x = pd.read_csv(D + "features/features_preprocessed.csv", index_col=0)
yf = pd.read_csv(D + "flat_labels/labels_flat_preprocessed.csv", index_col=0)
yh = pd.read_csv(D + "hierarchical_labels/mesh_labels_final.csv", index_col=0)
ix = pd.read_csv(R + "/inductive_splits_5fold.csv")   # 5-fold splits, generated by make_splits_5fold.py
ok = True
def chk(name, cond, info=""):
    global ok; ok &= bool(cond); print(("PASS " if cond else "FAIL ") + name, info)
# 2 alignment
chk("X/Yflat/Yhier have identical row ids in identical order", x.index.equals(yf.index) and x.index.equals(yh.index), f"n={len(x)}")
chk("row ids unique", x.index.is_unique)
chk("no NaN in X/Y", not (x.isna().any().any() or yf.isna().any().any() or yh.isna().any().any()))
chk("all 44 flat columns present in hierarchical columns, identical values", set(yf.columns) <= set(yh.columns) and (yh[yf.columns].values == yf.values).all())
# 1 splits
te_all = []
for k in range(1, 6):
    tr = ix[f"train_fold{k}"].dropna().astype(int).values; te = ix[f"test_fold{k}"].dropna().astype(int).values
    tr_ids, te_ids = set(x.index[tr]), set(x.index[te])
    chk(f"fold{k}: train/test row ids disjoint, union = all {len(x)}", not (tr_ids & te_ids) and len(tr_ids | te_ids) == len(x) and len(tr) == len(set(tr)), f"train={len(tr)} test={len(te)}")
    te_all += list(te_ids)
chk("every lncRNA is in exactly one test fold", len(te_all) == len(x) and len(set(te_all)) == len(x))
# 1b splits file provenance: format, 5 folds, test folds partition all rows, equals a fresh regeneration, authors' shipped file untouched
import subprocess, os
chk("splits file has exactly 5 train/test column pairs", list(ix.columns) == [f"{a}_fold{k}" for k in range(1, 6) for a in ("train", "test")])
chk("test folds are pairwise disjoint and cover 0..354", sorted(sum([list(ix[f"test_fold{k}"].dropna().astype(int)) for k in range(1, 6)], [])) == list(range(len(x))))
subprocess.run([sys.executable, R + "/make_splits_5fold.py", "5", AC + "/../regen5_check.csv"], check=True)
chk("splits file identical to a fresh run of make_splits_5fold.py (MultilabelStratifiedKFold(5, shuffle, seed 0) on hierarchical Y)", pd.read_csv(AC + "/../regen5_check.csv").equals(ix))
chk("fold sizes balanced (71 test rows each)", all(ix[f"test_fold{k}"].notna().sum() == 71 for k in range(1, 6)))
# 3 predictions
for tag, y, sub in [("MLC", yf, "predictions_mlc/labels_flat_preprocessed"), ("HMC", yh, "predictions_hmc/mesh_labels_final")]:
    for k in range(1, 6):
        p = pd.read_csv(f"{PR}/{sub}_IPCARF_inductive_multilabel_predictions_test_fold{k}.csv")
        nte = ix[f"test_fold{k}"].notna().sum()
        chk(f"{tag} fold{k}: predictions shape = (n_test, n_labels), finite, within [0,1]", p.shape == (nte, y.shape[1]) and np.isfinite(p.values).all() and p.values.min() >= 0 and p.values.max() <= 1, str(p.shape))
# 4 threshold: independent Youden re-implementation on TEST fold of the flat 44 labels vs Evaluator
ev = Evaluator()
for k in (1, 3, 5):
    te = ix[f"test_fold{k}"].dropna().astype(int).values
    yt = yf.iloc[te]; pm = pd.read_csv(f"{PR}/predictions_hmc/mesh_labels_final_IPCARF_inductive_multilabel_predictions_test_fold{k}.csv")
    pm.columns = yh.columns; pf = pm[yf.columns]                                   # authors' evaluate_flat_mesh mapping
    th = ev.sensivity_specifity_cutoff(yt, pf)
    mine = []
    for c in yf.columns:
        yc, sc = yt[c].values, pf[c].values
        if yc.min() == yc.max(): mine.append(0.5); continue
        fpr, tpr, t = roc_curve(yc, sc); j = tpr - fpr; mine.append(t[np.nanargmax(j)] if j.sum() > 0 else 0.5)
    chk(f"fold{k}: per-label Youden thresholds (44, one per label, from TEST labels) match independent recomputation", len(th) == 44 and np.allclose(th, mine))
    yt2 = yt.copy(); yt2.iloc[:, 0] = 1 - yt2.iloc[:, 0]
    chk(f"fold{k}: thresholds react to the test labels (fitted on test fold)", ev.sensivity_specifity_cutoff(yt2, pf) != th)
    chk(f"fold{k}: thresholds differ across labels", len(set(np.round(th, 6))) > 10, f"{len(set(np.round(th, 6)))} distinct")
    m = ev.evaluate_flat_mesh(yt, pf, pm)
    chk(f"fold{k}: HMC evaluation uses exactly the 44 flat columns; AUROC/AUPRC match sklearn on those columns", np.isclose(m[2], roc_auc_score(yt, pf, average="micro")) and np.isclose(m[3], average_precision_score(yt, pf, average="micro")) and pf.shape[1] == 44)
print("\nALL CHECKS PASSED" if ok else "\nSOME CHECKS FAILED"); sys.exit(0 if ok else 1)
