from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


PROJECT_ROOT = Path(__file__).resolve().parents[1]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Combine within-version inductive feature results and transfer/common-space "
            "results into final comparison tables."
        )
    )
    parser.add_argument(
        "--within-summary",
        default="lncRNA_CIBCB2025-main/parse_results/feature_representations/inductive_feature_representation_summary.csv",
        help="Summary generated by evaluate_inductive_experiments.py",
    )
    parser.add_argument(
        "--transfer-summary",
        default="lncRNA_CIBCB2025-main/parse_results/transfer_feature_representations/transfer_feature_representation_summary.csv",
        help="Summary generated by run_inductive_transfer_experiments.py",
    )
    parser.add_argument(
        "--outdir",
        default="Data/output_data/comparison_reports/inductive_feature_comparisons",
        help="Directory for merged comparison tables.",
    )
    return parser.parse_args()


def load_optional_csv(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


def normalize_within_summary(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return df
    out = df.copy()
    out["experiment"] = out["version"].map({"v1": "within_v1_cv", "v2": "within_v2_cv"})
    out["source_version"] = out["version"]
    out["target_version"] = out["version"]
    out["comparison_group"] = "within_version_cv"
    return out


def normalize_transfer_summary(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return df
    out = df.copy()
    out["comparison_group"] = out["experiment"].map(
        lambda value: "cross_version_transfer" if str(value).endswith("_transfer") else "target_common_cv"
    )
    return out


def add_rankings(df: pd.DataFrame, metric: str, ascending: bool) -> pd.DataFrame:
    ranked = df.copy()
    ranked[f"{metric}_rank"] = (
        ranked.groupby(["experiment", "model"])[f"{metric}_mean"]
        .rank(method="dense", ascending=ascending)
        .astype(int)
    )
    return ranked


def main() -> None:
    args = parse_args()
    within_path = PROJECT_ROOT / args.within_summary
    transfer_path = PROJECT_ROOT / args.transfer_summary
    outdir = PROJECT_ROOT / args.outdir
    outdir.mkdir(parents=True, exist_ok=True)

    within = normalize_within_summary(load_optional_csv(within_path))
    transfer = normalize_transfer_summary(load_optional_csv(transfer_path))

    combined = pd.concat([df for df in [within, transfer] if not df.empty], ignore_index=True)
    if combined.empty:
        raise FileNotFoundError(
            "No within-version or transfer summary CSVs were found. "
            "Run the evaluation scripts first."
        )

    combined = add_rankings(combined, "fscore", ascending=False)
    combined = add_rankings(combined, "micro_auprc", ascending=False)
    combined = add_rankings(combined, "hamming", ascending=True)
    combined = add_rankings(combined, "label_ranking", ascending=True)
    combined = combined.sort_values(
        ["comparison_group", "experiment", "model", "feature_set"], kind="stable"
    )

    by_fscore = combined.sort_values(
        ["experiment", "model", "fscore_rank", "micro_auprc_rank", "feature_set"],
        kind="stable",
    )
    by_auprc = combined.sort_values(
        ["experiment", "model", "micro_auprc_rank", "fscore_rank", "feature_set"],
        kind="stable",
    )

    combined_path = outdir / "combined_feature_summary.csv"
    by_fscore_path = outdir / "feature_ranking_by_fscore.csv"
    by_auprc_path = outdir / "feature_ranking_by_micro_auprc.csv"

    combined.to_csv(combined_path, index=False)
    by_fscore.to_csv(by_fscore_path, index=False)
    by_auprc.to_csv(by_auprc_path, index=False)

    print(f"Saved {combined_path}")
    print(f"Saved {by_fscore_path}")
    print(f"Saved {by_auprc_path}")


if __name__ == "__main__":
    main()
